import {startCanvas} from "./server.mjs";
const instance=await startCanvas({onPrompt:async target=>{
  const state=await instance.broker.call("state");
  const x=Math.max(0,...state.scene.objects.filter(n=>!n.parent).map(n=>n.x+n.w))+180;
  return instance.broker.call("batch",{expectedRevision:state.revision,expectedEpoch:state.bridgeEpoch,commands:[{command:"object.upsert",object:{id:"demo-agent-detail",type:"text",x,y:0,w:800,h:400,props:{label:"SIMULATED AGENT",title:"Details for "+target,text:"This response was generated by the deterministic provider, not an LLM."}}}]});
}});
console.log("Open "+instance.url);
const timer=setInterval(async()=>{
  if(!instance.broker.connected())return;
  clearInterval(timer);
  setTimeout(async()=>{
    try{const s=await instance.broker.call("state");await instance.broker.call("batch",{expectedRevision:s.revision,expectedEpoch:s.bridgeEpoch,commands:[{command:"object.upsert",object:{id:"demo-proactive",type:"text",x:1900,y:800,w:850,h:320,props:{label:"PROACTIVE UPDATE",title:"New sample finding",text:"This appeared without a human request."}}}]});console.log("Proactive update acknowledged");}catch(e){console.error(e.message);}
  },10000);
},500);
process.on("SIGINT",async()=>{clearInterval(timer);await instance.close();process.exit(0);});
